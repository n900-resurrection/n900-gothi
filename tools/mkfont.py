#!/usr/bin/env python3
"""Render a pixel TTF into the bitmap font table gothi/font.py (development tool, needs Pillow; the application itself does not).

    .venv/bin/python tools/mkfont.py assets/fonts/Tiny5-Regular.ttf 8 > gothi/font.py

Every glyph becomes (advance, rows): `rows` is a tuple of HEIGHT integers, bit 0 is the left column.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CHARS = "".join(chr(c) for c in range(32, 127)) + "áčďéěíňóřšťúůýžÁČĎÉĚÍŇÓŘŠŤÚŮÝŽ°"
path, size = sys.argv[1], int(sys.argv[2])
font = ImageFont.truetype(path, size)
ASC, DESC = 3, 3                      # rows above / below the line of the capitals kept in a glyph
base = font.getmetrics()[0]
height = base + DESC + ASC
glyphs = {}
for ch in CHARS:
    adv = max(1, round(font.getlength(ch)))
    w = adv + 4
    im = Image.new("1", (w, height + 4), 1)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, ASC), ch, font=font, fill=0)
    rows = []
    for y in range(height):
        bits = 0
        for x in range(adv):
            if im.getpixel((x, y)) == 0:
                bits |= 1 << x
        rows.append(bits)
    glyphs[ch] = (adv, tuple(rows))
print(f'"""Bitmap font generated by tools/mkfont.py from {path.split("/")[-1]} at {size} px. Do not edit."""')
print(f"HEIGHT = {height}")
print("CAP_TOP = 5      # row of the top of the capital letters in a glyph")
print(f"BASELINE = {ASC + base}      # row of the baseline in a glyph")
print("GLYPHS = {")
for ch, (adv, rows) in glyphs.items():
    print(f"    {ch!r}: ({adv}, {rows!r}),")
print("}")
